  function overlaps(placed, x0, y0, x1, y1) {
    for (var i = 0; i < placed.length; i++) { var p = placed[i]; if (x0 < p[2] && x1 > p[0] && y0 < p[3] && y1 > p[1]) return true; }
    return false;
  }
  function requestDraw() { if (!drawQueued) { drawQueued = true; requestAnimationFrame(function () { drawQueued = false; draw(); }); } }
  function seg(l, k, tx, ty) { ctx.moveTo(l.source.x * k + tx, l.source.y * k + ty); ctx.lineTo(l.target.x * k + tx, l.target.y * k + ty); }

  function draw() {
    if (!W || state.view !== 'map') return;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, W, H);
    var k = T.k, tx = T.x, ty = T.y, i, l, n;

    // dot grid that pans and zooms with the graph
    var gs = 34 * k; while (gs < 22) gs *= 2; while (gs > 44) gs /= 2;
    ctx.fillStyle = C.grid;
    for (var gx = ((tx % gs) + gs) % gs; gx < W; gx += gs) for (var gy = ((ty % gs) + gs) % gs; gy < H; gy += gs) ctx.fillRect(gx - 0.6, gy - 0.6, 1.2, 1.2);

    var f = state.hover && state.hover.vis ? state.hover : null, fs = null, pathMode = false;
    if (f) fs = focusSet(f);
    else if (state.path && state.path.set) { fs = { nodes: state.path.set, links: state.path.links }; pathMode = true; }
    else if (state.sel && state.sel.vis) { f = state.sel; fs = focusSet(f); }

    // edges: neutral for claim links, coloured by relationship type otherwise
    var groups = {}, dense = Math.max(0.45, Math.min(1, 1200 / (links.length + 1)));
    for (i = 0; i < links.length; i++) {
      l = links[i]; if (!l.vis || (fs && fs.links.has(l))) continue;
      var gk = (l.kind === 'rel' ? linkColor(l) : l.kind) + (l.unv || l.inferred ? '~' : '');
      (groups[gk] || (groups[gk] = [])).push(l);
    }
    ctx.lineWidth = 1;
    Object.keys(groups).forEach(function (gk) {
      var type = gk.replace('~', ''), dotted = gk.indexOf('~') > 0;
      ctx.setLineDash(type === 'parent' ? [6, 4] : dotted ? [2, 3] : []);
      if (C.r[type]) { ctx.strokeStyle = C.r[type]; ctx.globalAlpha = (fs ? 0.1 : 0.34) * dense; }
      else if (type === 'parent') { ctx.strokeStyle = C.labelDim; ctx.globalAlpha = fs ? 0.15 : 0.6; }
      else { ctx.strokeStyle = C.edge; ctx.globalAlpha = (fs ? 0.35 : 1) * dense; }
      ctx.beginPath(); groups[gk].forEach(function (l) { seg(l, k, tx, ty); }); ctx.stroke();
    });
    ctx.setLineDash([]);
    if (fs) {
      fs.links.forEach(function (l) {
        var direct = pathMode || l.source === f || l.target === f, type = linkColor(l);
        ctx.strokeStyle = type ? C.r[type] : l.kind === 'parent' ? C.label : C.accent;
        ctx.lineWidth = pathMode ? 2.2 : direct ? 1.5 : 1; ctx.globalAlpha = direct ? (type ? 0.95 : 0.6) : 0.5;
        ctx.setLineDash(l.kind === 'parent' ? [6, 4] : (l.unv || l.inferred) ? [2, 3] : []);
        ctx.beginPath(); seg(l, k, tx, ty); ctx.stroke();
      });
      ctx.setLineDash([]);
    }

    // nodes: entities first, then themes and claims on top
    var order = ['entity', 'theme', 'claim'];
    for (var o = 0; o < 3; o++) for (i = 0; i < nodes.length; i++) {
      n = nodes[i]; if (!n.vis || n.kind !== order[o]) continue;
      drawNode(n, fs && !fs.nodes.has(n) ? 0.14 : 1);
    }
    ctx.globalAlpha = 1;

    // labels, greedily placed by priority
    var cand = [], placed = [];
    for (i = 0; i < nodes.length; i++) {
      n = nodes[i]; if (!n.vis) continue;
      var sx = n.x * k + tx, sy = n.y * k + ty;
      if (sx < -60 || sy < -30 || sx > W + 60 || sy > H + 30) continue;
      var a = 1, pri = n.degree, text, lead = n === f || (pathMode && fs.nodes.has(n));
      if (fs) {
        if (!fs.nodes.has(n)) continue;
        var nr = rs(n) * (n.kind === 'claim' ? 1.1 : 0.9);
        if (nr > 3.5) placed.push([sx - nr, sy - nr, sx + nr, sy + nr]);
        pri += lead ? 1e6 : n.kind === 'claim' ? 500 : 0;
      } else if (n.kind === 'claim') { pri += 300; }
      else if (n.hub) { pri += 200; }
      else { a = Math.min(1, (k * n.r - 6.2) / 3.2); if (a <= 0.05) continue; }
      if (n.kind === 'claim') text = (fs || k > 1.25) ? n.id + '  ' + trunc(n.title, lead ? 60 : 34) : n.id;
      else text = trunc(n.name, lead ? 60 : n.kind === 'theme' ? 44 : 30);
      cand.push({ n: n, x: sx, y: sy, a: a, pri: pri, text: text, lead: lead });
    }
    cand.sort(function (p, q) { return q.pri - p.pri; });
    ctx.textAlign = 'center'; ctx.textBaseline = 'middle'; ctx.lineJoin = 'round';
    cand.forEach(function (c) {
      var big = c.lead || c.n.hub || c.n.kind === 'claim';
      var font = (c.lead ? '600 12.5px ' : big ? '500 11.5px ' : '400 11px ') + FONT;
      var w = textW(font, c.text), r = rs(c.n) * (c.n.kind === 'claim' ? (c.n.origin !== 'video' ? 1.75 : 1.25) : 1.05);
      var cx = w + 12 < W ? Math.min(Math.max(c.x, w / 2 + 6), W - w / 2 - 6) : c.x;   // keep the text on screen
      var y = c.y + r + 9, x0 = cx - w / 2 - 3, x1 = cx + w / 2 + 3;
      if (!c.lead && overlaps(placed, x0, y - 7, x1, y + 7)) return;
      placed.push([x0, y - 7, x1, y + 7]);
      ctx.font = font; ctx.globalAlpha = c.a;
      ctx.lineWidth = 3.5; ctx.strokeStyle = C.bg; ctx.strokeText(c.text, cx, y);
      ctx.fillStyle = big ? C.label : C.labelDim; ctx.fillText(c.text, cx, y);
    });
    ctx.globalAlpha = 1;

    // edge labels for the selected node or the traced path
    if (fs && (pathMode || f === state.sel)) {
      var efont = 'italic 400 11px ' + FONT, s = state.sel, labs = [];
      fs.links.forEach(function (l) {
        var text = '', type = linkColor(l);
        if (l.kind === 'rel') {
          var rr = l.rels.filter(relOn);
          if (!pathMode && s.kind === 'claim') rr = rr.filter(function (r) { return r.claims.indexOf(s.id) >= 0; });
          if (!rr.length) return;
          text = trunc(rr[0].label, 34) + (rr.length > 1 ? ' +' + (rr.length - 1) : '');
        } else if (l.kind === 'parent') text = 'follows up on';
        else if (pathMode) text = l.kind === 'theme' ? 'grouped under' : 'named in';
        else return;
        var ax = l.source.x * k + tx, ay = l.source.y * k + ty, bx = l.target.x * k + tx, by = l.target.y * k + ty;
        var len = Math.hypot(bx - ax, by - ay); if (len < 70) return;
        labs.push({ text: text, x: (ax + bx) / 2, y: (ay + by) / 2, len: len, direct: pathMode || l.source === s || l.target === s, col: type ? C.r[type] : C.label });
      });
      labs.sort(function (p, q) { return (q.direct - p.direct) || (q.len - p.len); });
      ctx.font = efont;
      labs.forEach(function (c) {
        var w = textW(efont, c.text), x0 = c.x - w / 2 - 4, x1 = c.x + w / 2 + 4;
        if (c.x < 0 || c.x > W || c.y < 0 || c.y > H || overlaps(placed, x0, c.y - 7, x1, c.y + 7)) return;
        placed.push([x0, c.y - 7, x1, c.y + 7]);
        ctx.lineWidth = 3.5; ctx.strokeStyle = C.bg; ctx.strokeText(c.text, c.x, c.y);
        ctx.fillStyle = c.col; ctx.fillText(c.text, c.x, c.y);
      });
    }
  }

