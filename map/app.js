    $('results').addEventListener('click', function (e) { var li = e.target.closest('li[data-i]'); if (li) pickResult(+li.dataset.i); });
    document.addEventListener('pointerdown', function (e) {
      if (!e.target.closest('.searchbox')) closeResults();
      if (narrow.matches && e.target === canvas && !$('main').classList.contains('rail-off')) showRail(false);
    });
