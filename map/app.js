  function closeResults() { $('results').hidden = true; $('search').setAttribute('aria-expanded', 'false'); }
  function runSearch(q) {
    q = q.trim().toLowerCase();
    var box = $('results'), input = $('search');
    if (!q) { closeResults(); results = []; return; }
    var terms = q.split(/\s+/);
    results = searchIndex.map(function (s) {
      var score = 0;
      for (var i = 0; i < terms.length; i++) {
        var t = terms[i];
        if (s.name.indexOf(t) === 0 || s.name.indexOf(' ' + t) >= 0) score += 6;
        else if (s.name.indexOf(t) >= 0) score += 4;
        else if (s.alt.indexOf(t) >= 0) score += 3;
        else if (s.text.indexOf(t) >= 0) score += 1;
        else return null;
      }
      var nm = (s.n.name || '').toLowerCase(), id = String(s.n.id || '').toLowerCase();
      if (nm === q || id === q) score += 20; else if (nm.indexOf(q) === 0) score += 8;
      return { n: s.n, score: score + Math.min(s.n.degree, 40) / 40 };
    }).filter(Boolean).sort(function (a, b) { return b.score - a.score; }).slice(0, 12);
    active = results.length ? 0 : -1;
    box.innerHTML = results.length ? results.map(function (r, i) {
      var n = r.n;
      return '<li role="option" id="res-' + i + '" data-i="' + i + '" aria-selected="' + (i === active) + '">' + nodeGlyph(n, 14) + '<span class="r-name">' + esc(n.kind === 'claim' ? n.id + ' ' + n.title : n.name) + '</span><span class="r-kind">' +
        (n.kind === 'claim' ? (n.verdict === 'unverified' ? (n.single_source ? 'Unverified, single source' : 'Unverified allegation') : VLABEL[n.verdict]) : n.kind === 'theme' ? 'Theme' : TLABEL[n.type]) + '</span></li>';
    }).join('') : '<li class="empty">Nothing matches “' + esc(q) + '”. Try a surname, a company name or a claim number such as C05.</li>';
    box.hidden = false; input.setAttribute('aria-expanded', 'true');
    input.setAttribute('aria-activedescendant', active >= 0 ? 'res-0' : '');
  }
  function pickResult(i) {
    var r = results[i]; if (!r) return;
    closeResults(); $('search').value = ''; $('search').blur();
    if (state.view !== 'map') setView('map', true);
    select(r.n);
  }

