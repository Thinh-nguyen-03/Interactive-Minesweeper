    $('hint-close').addEventListener('click', function () { $('hint').hidden = true; store('tcm-hint', 'off'); });
    $('panel-close').addEventListener('click', function () { if (state.sel) deselect(); else openPanel(false); });
    $('panel-size').addEventListener('click', function () {
      var tall = $('panel').classList.toggle('tall'); this.setAttribute('aria-pressed', String(tall));
      this.setAttribute('aria-label', tall ? 'Shrink panel' : 'Expand panel');
    });
    $('filters').addEventListener('submit', function (e) { e.preventDefault(); });
    $('filters').addEventListener('change', function (e) {
      var t = e.target; if (!t.dataset || !t.dataset.group) return;
      if (t.checked) F[t.dataset.group].add(t.value); else F[t.dataset.group].delete(t.value);
      t.closest('.frow').classList.toggle('off', !t.checked);
      applyFilters(); if (state.sel) renderPanel();
    });
    document.addEventListener('click', function (e) {
      var el = e.target.closest ? e.target.closest('[data-key],[data-act],[data-rank],[data-tab],[data-goto]') : null;
      if (!el) return;
      var act = el.dataset.act;
      if (el.dataset.goto) {
        var target = $(el.dataset.goto);
        if (target) target.scrollIntoView({ block: 'start', behavior: reduced.matches ? 'auto' : 'smooth' });
        return;
      }
      if (el.dataset.tab) return setTab(el.dataset.tab);
      if (el.dataset.rank) { state.rankBy = el.dataset.rank; return renderCommonView(); }
      if (act === 'reset-filters') return resetFilters();
      if (act === 'close-filters') return showRail(false);
      if (act === 'reset-view') { state.iso = null; return resetFilters(); }
      if (act === 'iso-clear') { state.iso = null; applyFilters(); if (state.sel) renderPanel(); return fit(true); }
      if (act === 'iso-more') { state.iso.depth++; applyFilters(); return fit(true); }
      if (act === 'path-clear') { state.path = null; state.pathFrom = null; renderBanner(); return requestDraw(); }
      if (act === 'isolate' && state.sel) { if (state.view !== 'map') setView('map', true); if (narrow.matches) openPanel(false); return isolate(state.sel); }
      if (act === 'show-on-graph' && state.sel) { setView('map', true); return focusOn(state.sel, false); }
      if (act === 'path-start' && state.sel) {
        state.pathFrom = state.sel; state.path = null;
        if (state.view !== 'map') setView('map', true);
        if (narrow.matches) openPanel(false);
        renderBanner(); return requestDraw();
      }
      var n = byKey.get(el.dataset.key); if (n) select(n);
    });

